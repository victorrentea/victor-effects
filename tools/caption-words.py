#!/usr/bin/env python3
"""Regenerate Sources/VictorEffects/SoundCaptionWords.swift from the reviewed
karaoke timings in tools/caption-words.json.

    python3 tools/caption-words.py

`caption-words.json` is the source of truth: per clip, each sung or spoken cue
(`at`, the line's start as `SoundCaptions.schedule` has it; `text`, the line as
drawn) with one onset per word, in seconds into the clip — the moment the word
starts being heard. It is written by REVIEW, not by a model's first guess:
`tools/caption-align.py` drafts each clip (Demucs vocals, MMS forced alignment,
Whisper, vocal onsets, a spectrogram) and a reviewer settles every word on the
picture (2026-10-23: Whisper alone lit "back again" 0.8 s into a silence).

Checks every cue against the running app (`GET /sounds/captions`) when it is up,
so a line edited since its review is reported instead of silently generated.
"""
import json, os, sys, urllib.request

BASE = os.environ.get("EFFECTS_URL", "http://127.0.0.1:55124")
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "caption-words.json")
OUT = os.path.join(HERE, "..", "Sources", "VictorEffects", "SoundCaptionWords.swift")


def words_of(text):
    """The caption's words, exactly as `SoundCaptions.wordEnds` counts them."""
    return [t for t in text.split() if any(c.isalnum() for c in t)]


def main():
    table = json.load(open(SRC))
    try:
        served = json.load(urllib.request.urlopen(BASE + "/sounds/captions", timeout=5))
    except OSError:
        served = None
        print("app not running — cues not checked against /sounds/captions", file=sys.stderr)
    bad = 0
    for asset, cues in table.items():
        if len({c["at"] for c in cues}) != len(cues):
            print(f"✗ {asset}: two cues at the same `at`", file=sys.stderr)
            bad += 1
        for cue in cues:
            if len(cue["words"]) != len(words_of(cue["text"])) or cue["words"] != sorted(cue["words"]):
                print(f"✗ {asset} @{cue['at']} \"{cue['text']}\": onsets not one per word, in order", file=sys.stderr)
                bad += 1
            if served is not None and not any(abs(c["start"] - cue["at"]) < 0.01 and c["text"] == cue["text"]
                                              for c in served.get(asset, {}).get("cues", [])):
                print(f"✗ {asset} @{cue['at']} \"{cue['text']}\": no such cue served — re-review it", file=sys.stderr)
                bad += 1
    if bad:
        sys.exit(1)

    lines = []
    for asset in sorted(table):
        rows = ",\n".join(f"            ({c['at']:g}, [{', '.join(f'{x:g}' for x in c['words'])}])" for c in table[asset])
        lines.append(f'        "{asset}": [\n{rows}],')
    swift = f"""import Foundation

// GENERATED by tools/caption-words.py from tools/caption-words.json — do not
// edit by hand; review the clip (tools/caption-align.py), edit the JSON, rerun.

extension SoundCaptions {{
    /// When each word of a spoken or sung cue starts being heard, in seconds
    /// into the clip: per asset, the cue's start (`CaptionLine.at`) and one
    /// onset per word as `wordEnds` counts them, reviewed on the isolated
    /// voice. A cue not listed — a [noise], an instrumental title — has no
    /// words said and never fills.
    static let wordTimes: [String: [(at: TimeInterval, words: [TimeInterval])]] = [
{chr(10).join(lines)}
    ]
}}
"""
    open(OUT, "w").write(swift)
    print(f"wrote {os.path.normpath(OUT)}: {sum(len(v) for v in table.values())} timed cues", file=sys.stderr)


if __name__ == "__main__":
    main()
